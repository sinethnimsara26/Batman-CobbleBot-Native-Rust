#!/usr/bin/env python3
"""B20: original source Level 2A Labs (#1317/#1316/#1402) scenery, mask & object separator."""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from bake_level_tiles import load_bitmaps
from bake_sprite_frames import load_shapes, load_text_defs
from labs_scenery_baker import (
    CANONICAL_SWF_SHA256,
    LabsStageSpec,
    emit_labs_rust_objects,
    render_hq3x_comparisons,
    separate_game_objects,
    sha256_bytes,
    verify_ground_mask,
    verify_root_backdrop_black,
)

LEVEL2A_SPEC = LabsStageSpec(
    batch="B20",
    level_key="level2a",
    root_frame=23,
    game_id=1402,
    level_id=1317,
    ground_id=1316,
    level_origin=(1210.1, 238.25),
    expected_player_spawn=(227.2, 115.4),
    expected_ground_origin=(-1542, -2307),
    expected_ground_size=(8781, 10060),
    expected_ground_pixels=19922753,
    expected_1x_tiles=177,
    sample_coords=(
        ("rooftop", 0, 0),
        ("upper_lab", 1800, 2400),
        ("mid_lab", 4800, 3600),
        ("tv_exit", 4200, 6800),
    ),
    checkpoint_prefix="checkpoint_2a",
    expected_counts={
        "doors": 18,
        "elevators": 3,
        "checkpoints": 4,
        "cameras": 10,
        "goons": 9,
        "eagles": 1,
        "health_pickups": 1,
        "batarang_pickups": 9,
        "door_jambs": 18,
        "lavas": 0,
    },
    open_check_pts=((227.2, 115.4),),
    solid_check_pts=((160.0, 115.4), (510.0, 115.4)),
)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("swf", type=Path)
    ap.add_argument("symbols_json", type=Path)
    ap.add_argument("bitmaps_dir", type=Path)
    ap.add_argument("mask_manifest", type=Path)
    ap.add_argument("mask_png", type=Path)
    ap.add_argument("tiles_dir", type=Path)
    ap.add_argument("tiles_bin", type=Path)
    ap.add_argument("outdir", type=Path)
    ap.add_argument("--emit-rust-objects", type=Path, required=True)
    args = ap.parse_args()

    swf_sha = sha256_bytes(args.swf.read_bytes())
    assert swf_sha == CANONICAL_SWF_SHA256, swf_sha
    symbols = json.loads(args.symbols_json.read_text(encoding="utf-8"))
    unsup: set[str] = set()
    shapes = load_shapes(args.swf, unsup)
    assert not unsup, unsup
    load_text_defs(args.swf)
    bitmaps = load_bitmaps(args.bitmaps_dir)

    args.outdir.mkdir(parents=True, exist_ok=True)
    backdrop_info = verify_root_backdrop_black(symbols, shapes, bitmaps)
    ground_info = verify_ground_mask(LEVEL2A_SPEC, args.mask_manifest, args.mask_png)
    multifloor = render_hq3x_comparisons(
        LEVEL2A_SPEC, symbols, shapes, bitmaps, args.tiles_dir, args.tiles_bin, args.outdir,
    )
    objs = separate_game_objects(LEVEL2A_SPEC, symbols)
    emit_labs_rust_objects(
        objs,
        "Auto-generated by b20_bake_labs2a_scenery.py from canonical #1402 (Level 2A).",
        args.emit_rust_objects,
        include_lavas=False,
    )

    report = {
        "batch": LEVEL2A_SPEC.batch,
        "source_swf_sha256": swf_sha,
        "root_frame": LEVEL2A_SPEC.root_frame,
        "game_symbol": LEVEL2A_SPEC.game_id,
        "level_symbol": LEVEL2A_SPEC.level_id,
        "level_origin": list(LEVEL2A_SPEC.level_origin),
        "backdrop": backdrop_info,
        "ground": ground_info,
        "tile_pack": {
            "count": LEVEL2A_SPEC.expected_1x_tiles,
            "bytes": args.tiles_bin.stat().st_size,
            "sha256": sha256_bytes(args.tiles_bin.read_bytes()),
        },
        "multifloor_1x_vs_hq3x": multifloor,
        "separated_object_counts": {k: len(v) for k, v in objs.items() if isinstance(v, list)},
        "separated_objects": objs,
    }
    (args.outdir / "labs2a-scenery-report.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8",
    )
    print(
        "B20 Labs 2A (#1317/#1316/#1402) verified:",
        f"tiles={LEVEL2A_SPEC.expected_1x_tiles},",
        f"ground={LEVEL2A_SPEC.expected_ground_size[0]}x{LEVEL2A_SPEC.expected_ground_size[1]},",
        f"doors={len(objs['doors'])}, elevators={len(objs['elevators'])},",
        f"goons={len(objs['goons'])}, eagle={len(objs['eagles'])},",
        f"cameras={len(objs['cameras'])}, checkpoints={len(objs['checkpoints'])},",
        f"pickups=1+{len(objs['batarang_pickups'])}",
    )


if __name__ == "__main__":
    main()
