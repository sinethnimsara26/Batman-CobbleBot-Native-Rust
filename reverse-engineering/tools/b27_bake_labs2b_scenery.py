#!/usr/bin/env python3
"""B27: original source Level 2B Labs (#1485/#1484/#1496) scenery, mask & object separator.

Development-only offline source extraction & verification from canonical cobblebot.swf:
- Validates root frame 25 (`#14` solid black root backdrop, `#1496` game clip, `#1485`
  level placement `(1210.1, 238.25)`, `player` spawn `(4413.7, 6854.3)` facing `+1`).
- Validates `#1484` collision mask (`8781x10060`, origin `(-1542, -2307)`, `16,245,474` px).
- Validates the full 145-tile 1x `assets/level2b_tiles.bin` / `manifest.json` bake
  (`#1485` excl. `#1484`, `--include-source-static-text`) with zero unsupported fills/missing glyphs.
- Renders sampled HQ3x (6x supersampled Lanczos -> 3x) vs 1x comparisons at 4 multi-floor
  vertical locations (`(4200,6800)`, `(7200,6800)`, `(4800,3200)`, `(0,0)`) over `#14` black.
- Separates `#1496` dynamic & foreground objects (`16` doors, `3` UP elevators, `4` checkpoints,
  `10` cameras, `1` `lava1` `#1486`, `10` `item_br*`, `16` front door jambs `#1394/#1395`, `#1495` `halo`)
  and emits typed `assets/labs2b_objects.rs` + `labs2b-scenery-report.json`.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

from bake_level_tiles import load_bitmaps
from bake_sprite_frames import load_shapes, load_text_defs
from labs_scenery_baker import (
    CANONICAL_SWF_SHA256,
    LabsStageSpec,
    emit_labs_rust_objects,
    render_hq3x_comparisons,
    separate_game_objects,
    sha256_bytes,
    verify_ground_mask,
    verify_root_backdrop_black,
)

LEVEL2B_SPEC = LabsStageSpec(
    batch="B27",
    level_key="level2b",
    root_frame=25,
    game_id=1496,
    level_id=1485,
    ground_id=1484,
    level_origin=(1210.1, 238.25),
    expected_player_spawn=(4413.7, 6854.3),
    expected_ground_origin=(-1542, -2307),
    expected_ground_size=(8781, 10060),
    expected_ground_pixels=16245474,
    expected_1x_tiles=145,
    sample_coords=(
        ("spawn_tv", 4200, 6800),
        ("east_shaft", 7200, 6800),
        ("mid_corridor", 4800, 3200),
        ("exit_roof", 0, 0),
    ),
    checkpoint_prefix="checkpoint_2b",
    expected_counts={
        "doors": 16,
        "elevators": 3,
        "checkpoints": 4,
        "cameras": 10,
        "goons": 0,
        "eagles": 0,
        "health_pickups": 0,
        "batarang_pickups": 10,
        "door_jambs": 16,
        "lavas": 1,
    },
    open_check_pts=((4413.7, 6854.3),),
    solid_check_pts=((4093.0, 7050.0), (4413.7, 7154.3)),
)


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("swf", type=Path)
    ap.add_argument("symbols_json", type=Path)
    ap.add_argument("bitmaps_dir", type=Path)
    ap.add_argument("mask_manifest", type=Path)
    ap.add_argument("mask_png", type=Path)
    ap.add_argument("tiles_dir", type=Path)
    ap.add_argument("tiles_bin", type=Path)
    ap.add_argument("outdir", type=Path)
    ap.add_argument("--emit-rust-objects", type=Path, required=True)
    args = ap.parse_args()

    swf_sha = sha256_bytes(args.swf.read_bytes())
    assert swf_sha == CANONICAL_SWF_SHA256, swf_sha
    symbols = json.loads(args.symbols_json.read_text(encoding="utf-8"))
    unsup: set[str] = set()
    shapes = load_shapes(args.swf, unsup)
    assert not unsup, unsup
    load_text_defs(args.swf)
    bitmaps = load_bitmaps(args.bitmaps_dir)

    args.outdir.mkdir(parents=True, exist_ok=True)
    backdrop_info = verify_root_backdrop_black(symbols, shapes, bitmaps)
    ground_info = verify_ground_mask(LEVEL2B_SPEC, args.mask_manifest, args.mask_png)
    multifloor = render_hq3x_comparisons(
        LEVEL2B_SPEC, symbols, shapes, bitmaps, args.tiles_dir, args.tiles_bin, args.outdir,
    )
    objs = separate_game_objects(LEVEL2B_SPEC, symbols)
    emit_labs_rust_objects(
        objs,
        "Auto-generated by b27_bake_labs2b_scenery.py from canonical #1496 (Level 2B).",
        args.emit_rust_objects,
        include_lavas=True,
    )

    report = {
        "batch": LEVEL2B_SPEC.batch,
        "source_swf_sha256": swf_sha,
        "root_frame": LEVEL2B_SPEC.root_frame,
        "game_symbol": LEVEL2B_SPEC.game_id,
        "level_symbol": LEVEL2B_SPEC.level_id,
        "level_origin": list(LEVEL2B_SPEC.level_origin),
        "backdrop": backdrop_info,
        "ground": ground_info,
        "tile_pack": {
            "count": LEVEL2B_SPEC.expected_1x_tiles,
            "bytes": args.tiles_bin.stat().st_size,
            "sha256": sha256_bytes(args.tiles_bin.read_bytes()),
        },
        "multifloor_1x_vs_hq3x": multifloor,
        "separated_object_counts": {k: len(v) for k, v in objs.items() if isinstance(v, list)},
        "separated_objects": objs,
    }
    (args.outdir / "labs2b-scenery-report.json").write_text(
        json.dumps(report, indent=2) + "\n", encoding="utf-8",
    )
    print(
        "B27 Labs 2B (#1485/#1484/#1496) verified:",
        f"tiles={LEVEL2B_SPEC.expected_1x_tiles},",
        f"ground={LEVEL2B_SPEC.expected_ground_size[0]}x{LEVEL2B_SPEC.expected_ground_size[1]},",
        f"doors={len(objs['doors'])}, elevators={len(objs['elevators'])},",
        f"cameras={len(objs['cameras'])}, checkpoints={len(objs['checkpoints'])},",
        f"lavas={len(objs['lavas'])}, pickups={len(objs['batarang_pickups'])}",
    )


if __name__ == "__main__":
    main()
