 // Record actual OS MCI device position next to game intro ticks.
 // Queries are never run without explicit external CI opt-in.
 fn trace_qa_audio(&mut self,reason:&str){
  let Some(log)=self.qa_audio_focus.as_mut() else{return;};
  let (mode,position,format,em,ep,ef)=self.audio.qa_intro_mci_status();
  let (open_error,open_message,file_written)=self.audio.qa_intro_open_diagnostics();
  let fade=self.game.intro_fadeout_tick.map(|f|f as i32).unwrap_or(-1);
  let _=writeln!(log.file,"{}\t{}\t{}\t{:?}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}\t{}",
   log.started.elapsed().as_millis(),reason,if self.active {1}else{0},
   self.game.screen,self.game.intro_tick,fade,mode,position,format,em,ep,ef,
   self.audio.qa_intro_transport(),open_error,open_message,if file_written{1}else{0});
  let _=log.file.flush();
  log.last=Instant::now();
 }
 fn sample_qa_audio_if_due(&mut self){
  if self.qa_audio_focus.as_ref().is_some_and(|log|log.last.elapsed()>=Duration::from_millis(180)){
   self.trace_qa_audio("sample");
  }
 }

 // WM_ACTIVATE and WM_KILLFOCUS can both fire for one click to the
 // taskbar. Transition just once, pausing only the Intro's MCI media.
 fn set_active(&mut self,active:bool){
  if self.active==active{return;}
  self.active=active;
  if active{
   // WinMM can take time to resume; frame clock begins AFTER it returns.
   // Otherwise a slow driver call causes a visible burst of stale ticks.
   resume_media_then_reset_visual_clock(
    || self.audio.on_focus_changed(true),
    &mut self.last,
    &mut self.acc,
   );
  }else{
   self.audio.on_focus_changed(false);
   self.intro_skip_armed=false;
   self.input.release_all();
   self.title_start_gate.reset();
   self.fullscreen_hotkeys.reset_on_focus_loss();
  }
  self.trace_qa_audio(if active{"focus_gain"}else{"focus_loss"});
 }
 unsafe fn poll_keyboard(&mut self,hwnd:HWND){
  // WM_ACTIVATE / WM_SETFOCUS are authoritative. GetForegroundWindow is
  // allowed to promote us to active, but a transient mismatch must not undo
  // a focus message and recreate the old "click around before keys work" bug.
  if GetForegroundWindow()==hwnd{self.set_active(true);}
  if !self.active{
   self.input.release_all();
   self.title_start_gate.reset();
   return;
  }
  // Capture both start-key levels once to avoid a race between reads.
  // In particular, Enter may still be held from a PowerShell launch.
  let enter_down=(GetAsyncKeyState(VK_ENTER as i32) as u16&0x8000)!=0;
  let space_down=(GetAsyncKeyState(VK_SPACE as i32) as u16&0x8000)!=0;
  let allow_start=if self.game.screen==AppScreen::Title{
   self.title_start_gate.allow(enter_down,space_down)
  }else{true};
  let escape_down=(GetAsyncKeyState(VK_ESCAPE as i32) as u16&0x8000)!=0;
  if !escape_down{self.fullscreen_escape_consumed=false;}
  for &k in KEYS.iter().chain(EXTRA_KEYS.iter()){
   let down=if k==VK_ENTER{enter_down}
     else if k==VK_ESCAPE{escape_down && self.fullscreen_windowed.is_none() && !self.fullscreen_escape_consumed}
     else if k==VK_SPACE{space_down}
     else{(GetAsyncKeyState(k as i32) as u16&0x8000)!=0};
   self.input.set(k,down && (allow_start || (k!=VK_ENTER && k!=VK_SPACE)));
  }
 }
 // Alt-tab and focus regain must not turn a pre-held F or Esc into an action.
 unsafe fn poll_fullscreen_hotkeys(&mut self,hwnd:HWND)->bool{
  if !self.active{self.fullscreen_hotkeys.reset_on_focus_loss();return false;}
  let f_down=(GetAsyncKeyState(0x46) as u16&0x8000)!=0; // VK_F
  let escape_down=(GetAsyncKeyState(VK_ESCAPE as i32) as u16&0x8000)!=0;
  match self.fullscreen_hotkeys.sample(f_down,escape_down,self.fullscreen_windowed.is_some()){
   FullscreenCommand::Enter=>self.enter_borderless_fullscreen(hwnd),
   FullscreenCommand::Exit=>{
    if self.restore_windowed(hwnd){
     // This same Esc press must NOT skip Intro or exit Instructions after restore.
     self.fullscreen_escape_consumed=true;
     self.input.set(VK_ESCAPE,false);
     self.input.clear_pressed();
     true
    }else{false}
   },
   FullscreenCommand::None=>false,
  }
 }
 unsafe fn enter_borderless_fullscreen(&mut self,hwnd:HWND)->bool{
  if self.fullscreen_windowed.is_some(){return false;}
  let style=GetWindowLongPtrW(hwnd,GWL_STYLE);
  if style==0{return false;}
  let mut saved:WINDOWPLACEMENT=zeroed();
  saved.length=size_of::<WINDOWPLACEMENT>() as u32;
  if GetWindowPlacement(hwnd,&mut saved)==0{return false;}
  let monitor=MonitorFromWindow(hwnd,MONITOR_DEFAULTTONEAREST);
  if monitor.is_null(){return false;}
  let mut info:MONITORINFO=zeroed();
  info.cbSize=size_of::<MONITORINFO>() as u32;
  if GetMonitorInfoW(monitor,&mut info)==0{return false;}
  let bounds=info.rcMonitor;
  if bounds.right<=bounds.left || bounds.bottom<=bounds.top{return false;}
  let borderless=(style & !(WS_OVERLAPPEDWINDOW as isize)) | (WS_POPUP as isize);
  if SetWindowLongPtrW(hwnd,GWL_STYLE,borderless)==0{return false;}
  // Mark fullscreen before resizing: synchronous DPI notifications must not
  // apply a windowed suggested rectangle over the monitor bounds.
  self.fullscreen_windowed=Some(WindowedState{style,placement:saved});
  FULLSCREEN_ACTIVE.store(true,Ordering::Relaxed);
  if SetWindowPos(hwnd,null_mut(),bounds.left,bounds.top,bounds.right-bounds.left,
                  bounds.bottom-bounds.top,
                  SWP_NOZORDER|SWP_NOOWNERZORDER|SWP_NOACTIVATE|SWP_FRAMECHANGED)==0{
   if let Some(previous)=self.fullscreen_windowed.take(){
    FULLSCREEN_ACTIVE.store(false,Ordering::Relaxed);
    SetWindowLongPtrW(hwnd,GWL_STYLE,previous.style);
    SetWindowPlacement(hwnd,&previous.placement);
    SetWindowPos(hwnd,null_mut(),0,0,0,0,SWP_NOMOVE|SWP_NOSIZE|
                 SWP_NOZORDER|SWP_NOOWNERZORDER|SWP_NOACTIVATE|SWP_FRAMECHANGED);
   }
   return false;
  }
  InvalidateRect(hwnd,null(),0);
  true
 }
 unsafe fn restore_windowed(&mut self,hwnd:HWND)->bool{
  let Some(previous)=self.fullscreen_windowed.as_ref() else{return false;};
  if SetWindowLongPtrW(hwnd,GWL_STYLE,previous.style)==0{return false;}
  FULLSCREEN_ACTIVE.store(false,Ordering::Relaxed);
  let placement_ok=SetWindowPlacement(hwnd,&previous.placement)!=0;
  let frame_ok=SetWindowPos(hwnd,null_mut(),0,0,0,0,SWP_NOMOVE|SWP_NOSIZE|
                  SWP_NOZORDER|SWP_NOOWNERZORDER|SWP_NOACTIVATE|SWP_FRAMECHANGED)!=0;
  if !placement_ok || !frame_ok{FULLSCREEN_ACTIVE.store(true,Ordering::Relaxed);return false;}
  self.fullscreen_windowed=None;
  InvalidateRect(hwnd,null(),0);
  true
 }
 /// Opt-in QA-only jumps: never mutate normal gameplay unless the developer
 /// explicitly launched the EXE with --qa-navigation. Return true if jumped.
 unsafe fn poll_qa_navigation(&mut self)->bool{
   if !self.qa_navigation || !self.active {
     self.qa_keys_were_down=[false;4];
     return false;
   }
   let mut jump=None;
   for (i,&key) in QA_SCENE_KEYS.iter().enumerate(){
     let down=(GetAsyncKeyState(key) as u16&0x8000)!=0;
     if down && !self.qa_keys_were_down[i] { jump=Some(i); }
     self.qa_keys_were_down[i]=down;
   }
   if let Some(scene)=jump{
     if scene!=3 {self.qa_hud_next=0;}
     if scene==0 {self.title_start_gate.reset();}
     self.game=Game::new();
     self.input.release_all();
     self.intro_skip_armed=false;
     self.acc=0.0;
     self.last=Instant::now();
     // Stop previous scene audio without repeatedly closing/reopening MCI
     // aliases: Audio owns the MCI devices for the whole application lifetime.
     self.audio.handle(AudioEvent::IntroStop);
     self.audio.handle(AudioEvent::MusicStop);
     match scene {
       0=>{}, // F5: reset to title
       1=>{  // F6: intro at its original first frame
         self.game.screen=AppScreen::Intro;
         self.audio.handle(AudioEvent::IntroStart);
       },
       2|3=>{ // F7 ordinary QA; F8 QA-only deterministic multi-value HUD.
         self.game.prepare_level1a_for_qa(&self.ground);
         if scene==3 {
           let (batarangs,lives,score)=QA_HUD_CASES[self.qa_hud_next];
           self.game.batarangs=batarangs;
           self.game.lives=lives;
           self.game.score=score;
           self.qa_hud_next=(self.qa_hud_next+1)%QA_HUD_CASES.len();
         }
         for event in self.game.take_audio_events(){self.audio.handle(event);}
       },
       _=>unreachable!(),
     }
     return true;
   }
   false
 }
 fn timer(&mut self,hwnd:HWND)->bool{
   unsafe{self.poll_keyboard(hwnd);}
   if unsafe{self.poll_fullscreen_hotkeys(hwnd)} {
    self.last=Instant::now();
    return true;
   }
   if unsafe{self.poll_qa_navigation()} {return true;}
   let now=Instant::now();let dt=(now-self.last).as_secs_f32().min(0.2);self.last=now;
   if !self.active{self.sample_qa_audio_if_due();return false;}
   self.acc+=dt;
   let mut stepped=false;
   while self.acc>=FIXED_STEP{
     self.game.tick(&mut self.input,&self.ground);
     if let Some(next_stage)=self.game.consume_pending_stage_entry(){
       self.ground=CollisionMask::for_stage(next_stage);
       self.assets.load_stage(next_stage);
     }
     for event in self.game.take_audio_events(){self.audio.handle(event);}
     self.acc-=FIXED_STEP;
     stepped=true;
   }
   self.sample_qa_audio_if_due();
   stepped
 }
