// The launcher's Enter/Space key can remain physically down at the first
// Win32 keyboard poll. A release must be seen before accepting a fresh press.
#[derive(Default)]
struct TitleStartGate{armed:bool}
impl TitleStartGate{
 fn reset(&mut self){self.armed=false;}
 fn allow(&mut self,enter_down:bool,space_down:bool)->bool{
  if !self.armed && !enter_down && !space_down{self.armed=true;}
  self.armed
 }
}

#[derive(Debug,PartialEq,Eq)]
enum FullscreenCommand{None,Enter,Exit}
#[derive(Default)]
struct FullscreenHotkeys{f_released:bool,escape_released:bool}
impl FullscreenHotkeys{
 fn reset_on_focus_loss(&mut self){self.f_released=false;self.escape_released=false;}
 fn sample(&mut self,f_down:bool,escape_down:bool,is_fullscreen:bool)->FullscreenCommand{
  let cmd=if is_fullscreen && escape_down && self.escape_released{FullscreenCommand::Exit}
   else if !is_fullscreen && f_down && self.f_released{FullscreenCommand::Enter}
   else{FullscreenCommand::None};
  self.f_released=!f_down;
  self.escape_released=!escape_down;
  cmd
 }
}
// Preserve the OS window's original style and restored/maximized placement.
// Unlike WS_POPUP monitor sizing, WINDOWPLACEMENT also remembers maximization.
struct WindowedState{style:isize,placement:WINDOWPLACEMENT}

// A synchronous WinMM resume can block the UI thread. Never charge that
// media-driver delay to the next 25Hz animation update on regaining focus.
fn resume_media_then_reset_visual_clock(
    resume_media: impl FnOnce(),
    last: &mut Instant,
    acc: &mut f32,
){
    resume_media();
    *last=Instant::now();
    *acc=0.0;
}

// Only with BCB_FOCUS_QA_LOG set. Never creates output for an ordinary user.
struct AudioFocusQaLog{file:std::fs::File,started:Instant,last:Instant}
impl AudioFocusQaLog{
 fn from_env()->Option<Self>{
  let name=std::env::var_os("BCB_FOCUS_QA_LOG")?;
  let path=std::path::PathBuf::from(name);
  let mut file=std::fs::File::create(path).ok()?;
  let _=writeln!(file,"elapsed_ms\treason\tactive\tscreen\tintro_tick\tintro_fade_tick\tmci_mode\tmci_position\tmci_time_format\tmode_error\tposition_error\tformat_error\ttransport\topen_error\topen_message\tfile_written");
  let now=Instant::now();
  Some(Self{file,started:now,last:now})
 }
}

