fn with_app<R>(f: impl FnOnce(&mut App) -> R) -> Option<R> {
    UI_APP.with(|ui| ui.with_mut(f, App::set_active))
}
fn queue_focus(active: bool) {
    UI_APP.with(|ui| ui.enqueue_focus(active, App::set_active));
}

fn wide(s:&str)->Vec<u16>{s.encode_utf16().chain(Some(0)).collect()}

unsafe fn enable_best_dpi_awareness()->bool{
 // SetProcessDpiAwarenessContext was added after the legacy API. Resolve it
 // dynamically so older Windows versions can still start and use the fallback.
 let user32_name=wide("user32.dll");
 let user32=GetModuleHandleW(user32_name.as_ptr());
 if !user32.is_null(){
  let proc=GetProcAddress(user32,b"SetProcessDpiAwarenessContext\0".as_ptr());
  if !proc.is_null(){
   type SetProcessDpiAwarenessContextFn=unsafe extern "system" fn(*mut c_void)->i32;
   let set_context:SetProcessDpiAwarenessContextFn=transmute(proc);
   let context=DPI_AWARENESS_CONTEXT_PER_MONITOR_AWARE_V2 as *mut c_void;
   if set_context(context)!=0{return true;}
  }
 }
 SetProcessDPIAware()!=0
}

fn viewport_for_client(cw:i32,ch:i32)->(i32,i32,i32,i32){
 let cw=cw.max(1);let ch=ch.max(1);
 let(dw,dh)=if(cw as i64)*(LOGICAL_H as i64)<=(ch as i64)*(LOGICAL_W as i64){
  (cw,((cw as i64)*(LOGICAL_H as i64)/(LOGICAL_W as i64))as i32)
 }else{
  (((ch as i64)*(LOGICAL_W as i64)/(LOGICAL_H as i64))as i32,ch)
 };
 ((cw-dw)/2,(ch-dh)/2,dw,dh)
}
fn client_to_stage(cw:i32,ch:i32,px:i32,py:i32)->Option<(i32,i32)>{
    let(vx,vy,vw,vh)=viewport_for_client(cw,ch);
    if px<vx||px>=vx+vw||py<vy||py>=vy+vh{return None;}
    Some((
        ((px-vx) as i64*LOGICAL_W as i64/vw as i64) as i32,
        ((py-vy) as i64*LOGICAL_H as i64/vh as i64) as i32,
    ))
}
fn hit_skip_rect(cw:i32,ch:i32,px:i32,py:i32,rect:(i32,i32,i32,i32))->bool{
    let(left,top,right,bottom)=rect;
    client_to_stage(cw,ch,px,py).map(|(sx,sy)|
        sx>=left&&sx<right&&sy>=top&&sy<bottom
    ).unwrap_or(false)
}
fn hit_intro_skip(cw:i32,ch:i32,px:i32,py:i32)->bool{
    hit_skip_rect(cw,ch,px,py,INTRO_SKIP_RECT)
}
fn active_card_skip_rect(game:&Game)->Option<(i32,i32,i32,i32)>{
    match game.screen {
        AppScreen::Intro if game.intro_fadeout_tick.is_none()=>Some(INTRO_SKIP_RECT),
        AppScreen::EscapeCard if game.escape_card_fadeout_tick.is_none() && !game.escape_card_complete =>Some(ESCAPE_CARD_SKIP_RECT),
        _=>None,
    }
}
unsafe fn viewport(hwnd:HWND)->(i32,i32,i32,i32){let mut r:RECT=zeroed();GetClientRect(hwnd,&mut r);viewport_for_client(r.right-r.left,r.bottom-r.top)}
unsafe extern "system" fn wndproc(hwnd:HWND,msg:u32,w:WPARAM,l:LPARAM)->LRESULT {
 match msg {
  WM_ERASEBKGND=>1,
  WM_PAINT=>{
   let mut ps:PAINTSTRUCT=zeroed();
   let hdc=BeginPaint(hwnd,&mut ps);
   let painted=with_app(|app|{
    app.render();
    let mut r:RECT=zeroed();
    GetClientRect(hwnd,&mut r);
    let cw=(r.right-r.left).max(1);
    let ch=(r.bottom-r.top).max(1);
    let(vx,vy,vw,vh)=viewport(hwnd);
    if vy>0{
     PatBlt(hdc,0,0,cw,vy,BLACKNESS);
     PatBlt(hdc,0,vy+vh,cw,ch-vy-vh,BLACKNESS);
    }
    if vx>0{
     PatBlt(hdc,0,vy,vx,vh,BLACKNESS);
     PatBlt(hdc,vx+vw,vy,cw-vx-vw,vh,BLACKNESS);
    }
    let bmi=BITMAPINFO{
     bmiHeader:BITMAPINFOHEADER{
      biSize:size_of::<BITMAPINFOHEADER>() as u32,
      biWidth:app.fb.w as i32,biHeight:-(app.fb.h as i32),
      biPlanes:1,biBitCount:32,biCompression:BI_RGB,
      biSizeImage:app.fb.byte_len() as u32,
      biXPelsPerMeter:0,biYPelsPerMeter:0,biClrUsed:0,biClrImportant:0
     },
     bmiColors:[RGBQUAD{rgbBlue:0,rgbGreen:0,rgbRed:0,rgbReserved:0}]
    };
    SetStretchBltMode(hdc,HALFTONE);
    SetBrushOrgEx(hdc,0,0,null_mut());
    StretchDIBits(hdc,vx,vy,vw,vh,0,0,
      app.fb.w as i32,app.fb.h as i32,
      app.fb.pixels.as_ptr() as *const c_void,&bmi,DIB_RGB_COLORS,SRCCOPY);
   });
   EndPaint(hwnd,&ps);
   // A nested paint could not borrow App; request the next real paint.
   if painted.is_none(){InvalidateRect(hwnd,null(),0);}
   0
  },
  WM_TIMER=>{
   if with_app(|app|app.timer(hwnd)).unwrap_or(false){
    InvalidateRect(hwnd,null(),0);
   }
   0
  },
  WM_SETFOCUS=>{queue_focus(true);0},
  WM_KILLFOCUS=>{queue_focus(false);0},
  WM_ACTIVATE=>{queue_focus((w&0xffff)!=WA_INACTIVE);0},
  WM_LBUTTONDOWN=>{
   SetActiveWindow(hwnd);
   SetFocus(hwnd);
   let mx=(l as u32&0xffff) as u16 as i16 as i32;
   let my=((l as u32>>16)&0xffff) as u16 as i16 as i32;
   let mut client:RECT=zeroed();
   GetClientRect(hwnd,&mut client);
   with_app(|app|{
    // Source ButtonCondAction is release-inside, never mouse-down.
    app.intro_skip_armed=active_card_skip_rect(&app.game)
      .map(|rect|hit_skip_rect(client.right-client.left,client.bottom-client.top,mx,my,rect))
      .unwrap_or(false);
   });
   0
  },
  WM_LBUTTONUP=>{
   let mx=(l as u32&0xffff) as u16 as i16 as i32;
   let my=((l as u32>>16)&0xffff) as u16 as i16 as i32;
   let mut client:RECT=zeroed();
   GetClientRect(hwnd,&mut client);
   let skipped=with_app(|app|{
    let armed=app.intro_skip_armed;
    app.intro_skip_armed=false;
    let hit=armed && active_card_skip_rect(&app.game)
      .map(|rect|hit_skip_rect(client.right-client.left,client.bottom-client.top,mx,my,rect))
      .unwrap_or(false);
    if !hit { return false; }
    match app.game.screen {
     AppScreen::Intro=>app.game.skip_intro(),
     AppScreen::EscapeCard=>app.game.skip_escape_card(),
     _=>false,
    }
   }).unwrap_or(false);
   if skipped{InvalidateRect(hwnd,null(),0);}
   0
  },
  WM_DPICHANGED=>{
   if FULLSCREEN_ACTIVE.load(Ordering::Relaxed){
    InvalidateRect(hwnd,null(),0);
    return 0;
   }
   if l!=0{
    let r=&*(l as *const RECT);
    let width=(r.right-r.left).max(1);
    let height=(r.bottom-r.top).max(1);
    SetWindowPos(hwnd,null_mut(),r.left,r.top,width,height,SWP_NOZORDER|SWP_NOACTIVATE);
   }
   InvalidateRect(hwnd,null(),0);
   0
  },
  WM_CLOSE=>{DestroyWindow(hwnd);0},
  WM_DESTROY=>{KillTimer(hwnd,1);PostQuitMessage(0);0},
  _=>DefWindowProcW(hwnd,msg,w,l),
 }
}

pub fn run(qa_navigation:bool){
 unsafe {
  let _dpi_aware=enable_best_dpi_awareness();
  UI_APP.with(|ui|ui.install(App::new(qa_navigation)));
  let inst=GetModuleHandleW(null());
  let cls=wide("BatmanCobbleBotLevel1AFidelity");
  let title=wide("The Batman - CobbleBot Caper - Level 1A Fidelity Slice");
  let wc=WNDCLASSW{
   style:CS_HREDRAW|CS_VREDRAW,lpfnWndProc:Some(wndproc),
   cbClsExtra:0,cbWndExtra:0,hInstance:inst,
   hIcon:LoadIconW(inst,101_usize as *const u16),
   hCursor:LoadCursorW(null_mut(),IDC_ARROW),
   hbrBackground:null_mut(),lpszMenuName:null(),lpszClassName:cls.as_ptr()
  };
  if RegisterClassW(&wc)==0 {
   drop(UI_APP.with(|ui|ui.take()));
   return;
  }
  let hwnd=CreateWindowExW(0,cls.as_ptr(),title.as_ptr(),
    WS_OVERLAPPEDWINDOW|WS_VISIBLE,CW_USEDEFAULT,CW_USEDEFAULT,930,660,
    null_mut(),null_mut(),inst,null_mut());
  if hwnd.is_null(){
   drop(UI_APP.with(|ui|ui.take()));
   return;
  }
  ShowWindow(hwnd,SW_SHOW);
  SetActiveWindow(hwnd);
  SetForegroundWindow(hwnd);
  SetFocus(hwnd);
  UpdateWindow(hwnd);
  SetTimer(hwnd,1,8,null());
  let mut msg:MSG=zeroed();
  while GetMessageW(&mut msg,null_mut(),0,0)>0{
   TranslateMessage(&msg);
   DispatchMessageW(&msg);
  }
  // Return ownership only after the window has stopped dispatching messages.
  drop(UI_APP.with(|ui|ui.take()));
 }
}

